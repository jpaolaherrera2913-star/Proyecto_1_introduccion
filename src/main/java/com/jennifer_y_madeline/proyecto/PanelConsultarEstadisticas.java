    private final EstadisticasDAO estadisticasDAO = new EstadisticasDAO();

    private static class Datos {
        EstadisticasDAO.Resumen resumen;
        List<EstadisticasDAO.PorTipoCliente> tipos;
        List<EstadisticasDAO.PorMetodoPago> metodos;
    }

    private void configurarCampos() {
        JTextField[] campos = {txtRegulares, txtFrecuentes, txtCorporativos, txtTotalClientes,
            txtEfectivo, txtTarjeta, txtTransferencia, txtMetodoMasUsado};
        for (JTextField c : campos) {
            c.setEditable(false);
        }
        JProgressBar[] barras = {barRegulares, barFrecuentes, barCorporativos};
        for (JProgressBar b : barras) {
            b.setMinimum(0);
            b.setMaximum(100);
            b.setValue(0);
            b.setStringPainted(true);
        }
    }

    private void cargar() {
        final java.awt.Component padre = this;
        new SwingWorker<Datos, Void>() {
            @Override
            protected Datos doInBackground() {
                Datos d = new Datos();
                d.resumen = estadisticasDAO.resumen();
                d.tipos = estadisticasDAO.clasificacionClientes();
                d.metodos = estadisticasDAO.porMetodoPago();
                return d;
            }

            @Override
            protected void done() {
                try {
                    Datos d = get();
                    mostrarResumen(d.resumen);
                    mostrarClientes(d.tipos);
                    mostrarMetodos(d.metodos);
                } catch (Exception ex) {
                    ex.printStackTrace();
                    JOptionPane.showMessageDialog(padre,
                            "Error al cargar las estadísticas: " + ex.getMessage());
                }
            }
        }.execute();
    }

    private void mostrarResumen(EstadisticasDAO.Resumen r) {
        lblNumClientes.setText(String.valueOf(r.totalClientes()));
        lblNumVentas.setText(String.valueOf(r.totalVentas()));
        lblNumProductos.setText(String.valueOf(r.productosVendidos()));
        lblTotalVendido.setText(q(r.totalVendido()));
        lblPromedio.setText(q(r.promedio()));
        lblVentaMayor.setText(q(r.ventaMayor()));
        lblVentaMenor.setText(q(r.ventaMenor()));
    }

    private void mostrarClientes(List<EstadisticasDAO.PorTipoCliente> tipos) {
        long regulares = 0, frecuentes = 0, corporativos = 0;
        for (EstadisticasDAO.PorTipoCliente t : tipos) {
            String n = t.tipo() == null ? "" : t.tipo().toLowerCase();
            if (n.contains("regular")) {
                regulares += t.clientes();
            } else if (n.contains("frecuent")) {
                frecuentes += t.clientes();
            } else if (n.contains("corporat")) {
                corporativos += t.clientes();
            }
        }
        long total = regulares + frecuentes + corporativos;
        poner(txtRegulares, barRegulares, regulares, total);
        poner(txtFrecuentes, barFrecuentes, frecuentes, total);
        poner(txtCorporativos, barCorporativos, corporativos, total);
        txtTotalClientes.setText("Total: " + total + (total == 1 ? " cliente" : " clientes"));
    }

    private void poner(JTextField texto, JProgressBar barra, long cantidad, long total) {
        int porcentaje = total == 0 ? 0 : (int) Math.round(100.0 * cantidad / total);
        texto.setText(cantidad + (cantidad == 1 ? " cliente" : " clientes") + " (" + porcentaje + "%)");
        barra.setValue(porcentaje);
    }

    private void mostrarMetodos(List<EstadisticasDAO.PorMetodoPago> metodos) {
        EstadisticasDAO.PorMetodoPago efectivo = null, tarjeta = null, transferencia = null;
        long maximo = 0;
        for (EstadisticasDAO.PorMetodoPago m : metodos) {
            String n = m.metodo() == null ? "" : m.metodo().toLowerCase();
            if (n.contains("efectivo")) {
                efectivo = m;
            } else if (n.contains("tarjeta")) {
                tarjeta = m;
            } else if (n.contains("transferencia")) {
                transferencia = m;
            }
            maximo = Math.max(maximo, m.ventas());
        }
        txtEfectivo.setText(textoMetodo(efectivo));
        txtTarjeta.setText(textoMetodo(tarjeta));
        txtTransferencia.setText(textoMetodo(transferencia));

        List<String> empatados = new ArrayList<>();
        for (EstadisticasDAO.PorMetodoPago m : metodos) {
            if (maximo > 0 && m.ventas() == maximo) {
                empatados.add(m.metodo());
            }
        }
        String ventasTxt = maximo + (maximo == 1 ? " venta" : " ventas");
        String texto;
        if (empatados.isEmpty()) {
            texto = "Sin ventas registradas";
        } else if (empatados.size() == 1) {
            texto = empatados.get(0) + " (" + ventasTxt + ")";
        } else if (empatados.size() == 2) {
            texto = "Empate: " + empatados.get(0) + " y " + empatados.get(1) + " (" + maximo + " c/u)";
        } else {
            texto = "Empate: " + String.join(", ", empatados.subList(0, empatados.size() - 1))
                    + " y " + empatados.get(empatados.size() - 1);
        }
        txtMetodoMasUsado.setText(texto);
        txtMetodoMasUsado.setToolTipText(texto);
    }

    private String textoMetodo(EstadisticasDAO.PorMetodoPago m) {
        long ventas = m == null ? 0 : m.ventas();
        BigDecimal total = m == null ? BigDecimal.ZERO : m.total();
        return ventas + (ventas == 1 ? " venta" : " ventas") + "  ·  " + q(total);
    }

    private String q(BigDecimal monto) {
        return String.format(Locale.US, "Q%,.2f", monto);
    }


    public static boolean confirmar(java.awt.Component padre) {
        java.awt.Window ventana = padre == null ? null : javax.swing.SwingUtilities.getWindowAncestor(padre);
        PanelMensajeCierreCaja panel = new PanelMensajeCierreCaja();
        javax.swing.JDialog d = new javax.swing.JDialog(ventana, java.awt.Dialog.ModalityType.APPLICATION_MODAL);
        d.setUndecorated(true);
        panel.setBorder(javax.swing.BorderFactory.createLineBorder(new java.awt.Color(200, 190, 215)));
        d.setContentPane(panel);
        d.getRootPane().registerKeyboardAction(e -> d.dispose(),
                javax.swing.KeyStroke.getKeyStroke(java.awt.event.KeyEvent.VK_ESCAPE, 0),
                javax.swing.JComponent.WHEN_IN_FOCUSED_WINDOW);
        d.pack();
        d.setLocationRelativeTo(ventana);
        panel.dialogo = d;
        d.setVisible(true);
        return panel.confirmado;
    }


    public void recargar() {
        final Component padre = this;
        new SwingWorker<Datos, Void>() {
            @Override
            protected Datos doInBackground() {
                Datos d = new Datos();
                d.ventas = dao.listarResumenes();
                d.metodos = dao.listarMetodos();
                return d;
            }

            @Override
            protected void done() {
                try {
                    Datos d = get();
                    todas = d.ventas;
                    String actual = String.valueOf(cmbMetodo.getSelectedItem());
                    cmbMetodo.removeAllItems();
                    cmbMetodo.addItem("Todos");
                    for (MetodoPago m : d.metodos) {
                        cmbMetodo.addItem(m.getNombre());
                    }
                    cmbMetodo.setSelectedItem(actual);
                    if (cmbMetodo.getSelectedIndex() < 0) {
                        cmbMetodo.setSelectedIndex(0);
                    }
                    actualizarTarjetas();
                    llenarTabla(todas);
                    filtrar();
                } catch (Exception ex) {
                    ex.printStackTrace();
                    JOptionPane.showMessageDialog(padre, "Error al cargar las ventas: " + ex.getMessage());
                }
            }
        }.execute();
    }

    private void actualizarTarjetas() {
        int productos = 0;
        BigDecimal subtotal = BigDecimal.ZERO;
        BigDecimal descuentos = BigDecimal.ZERO;
        BigDecimal total = BigDecimal.ZERO;
        for (VentaResumen v : todas) {
            for (Venta l : v.getLineas()) {
                productos += l.getCantidad();
            }
            subtotal = subtotal.add(v.getTotal());
            descuentos = descuentos.add(descuento(v));
            total = total.add(totalFinal(v));
        }
        lblNumVentas.setText(String.valueOf(todas.size()));
        lblNumProductos.setText(String.valueOf(productos));
        lblSubtotal.setText(q(subtotal));
        lblDescuentos.setText(q(descuentos));
        lblTotal.setText(q(total));
    }

    private void filtrar() {
        String cliente = valor(txtCliente, PH_CLIENTE).toLowerCase();
        String metodo = String.valueOf(cmbMetodo.getSelectedItem());
        boolean todosMetodos = cmbMetodo.getSelectedIndex() <= 0;

        LocalDate fecha = null;
        String textoFecha = valor(txtFecha, PH_FECHA);
        if (!textoFecha.isEmpty()) {
            try {
                fecha = LocalDate.parse(textoFecha);
            } catch (DateTimeParseException ex) {
                JOptionPane.showMessageDialog(this,
                        "La fecha debe tener el formato AAAA-MM-DD (por ejemplo 2026-10-20).");
                return;
            }
        }

        List<VentaResumen> resultado = new ArrayList<>();
        for (VentaResumen v : todas) {
            if (!cliente.isEmpty() && !v.getCliente().getNombre().toLowerCase().contains(cliente)) {
                continue;
            }
            if (!todosMetodos && !v.getMetodoPago().getNombre().equals(metodo)) {
                continue;
            }
            if (fecha != null && !v.getFecha().toLocalDate().equals(fecha)) {
                continue;
            }
            resultado.add(v);
        }
        llenarTabla(resultado);
    }

    private void limpiar() {
        txtCliente.setText(PH_CLIENTE);
        txtCliente.setForeground(GRIS);
        txtFecha.setText(PH_FECHA);
        txtFecha.setForeground(GRIS);
        cmbMetodo.setSelectedIndex(0);
        llenarTabla(todas);
    }

    private void llenarTabla(List<VentaResumen> lista) {
        mostradas = new ArrayList<>(lista);
        modelo.setRowCount(0);
        for (VentaResumen v : mostradas) {
            modelo.addRow(new Object[]{
                v.getNumero(),
                v.getFecha().format(FORMATO_FECHA),
                v.getCliente().getNombre(),
                String.join(", ", v.getNombresProductos()),
                v.getMetodoPago().getNombre(),
                q(v.getTotal()),
                q(descuento(v)),
                q(totalFinal(v))
            });
        }
    }

    private VentaResumen seleccionada() {
        int fila = tblVentas.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione una venta de la tabla.");
            return null;
        }
        return mostradas.get(tblVentas.convertRowIndexToModel(fila));
    }

    private void verDetalle() {
        VentaResumen v = seleccionada();
        if (v == null) {
            return;
        }
        StringBuilder sb = new StringBuilder("<html><body style='width:380px'>");
        sb.append("<b>Venta N° ").append(v.getNumero()).append("</b><br>");
        sb.append("Fecha: ").append(v.getFecha().format(FORMATO_FECHA)).append("<br>");
        sb.append("Cliente: ").append(html(v.getCliente().getNombre()))
          .append(" (").append(html(v.getCliente().getTipoCliente().getNombre())).append(")<br>");
        sb.append("Método de pago: ").append(html(v.getMetodoPago().getNombre())).append("<br><br>");
        sb.append("<table cellpadding='2'><tr><td><b>Producto</b></td><td><b>Cant.</b></td>")
          .append("<td><b>Precio</b></td><td><b>Subtotal</b></td></tr>");
        for (Venta l : v.getLineas()) {
            BigDecimal sub = l.getPrecioUnitario().multiply(BigDecimal.valueOf(l.getCantidad()));
            sb.append("<tr><td>").append(html(l.getProducto().getNombre())).append("</td><td>")
              .append(l.getCantidad()).append("</td><td>").append(q(l.getPrecioUnitario()))
              .append("</td><td>").append(q(sub)).append("</td></tr>");
        }
        sb.append("</table><br>");
        sb.append("Subtotal: ").append(q(v.getTotal())).append("<br>");
        sb.append("Descuento: - ").append(q(descuento(v))).append("<br>");
        if (recargo(v).signum() > 0) {
            sb.append("Recargo (2%): ").append(q(recargo(v))).append("<br>");
        }
        sb.append("<b>Total: ").append(q(totalFinal(v))).append("</b>");
        sb.append("</body></html>");
        JOptionPane.showMessageDialog(this, new JLabel(sb.toString()), "Detalle de la venta",
                JOptionPane.PLAIN_MESSAGE);
    }

    private void eliminarVenta() {
        VentaResumen v = seleccionada();
        if (v == null) {
            return;
        }
        List<String> nombres = v.getNombresProductos();
        String producto = nombres.get(0) + (nombres.size() > 1 ? " +" + (nombres.size() - 1) + " más" : "");
        String detalle = producto + "  ·  " + v.getCliente().getNombre() + "  ·  " + q(totalFinal(v));

        if (!PanelMensajeEliminar.confirmar(this, "la venta", detalle)) {
            return;
        }
        try {
            dao.eliminarVenta(v.getIdsLineas(), true);
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "No se pudo eliminar la venta: " + ex.getMessage());
            return;
        }
        recargar();
    }

    private BigDecimal descuento(VentaResumen v) {
        BigDecimal suma = BigDecimal.ZERO;
        for (Venta l : v.getLineas()) {
            if (l.getDescuento() != null) {
                suma = suma.add(l.getDescuento());
            }
        }
        return suma;
    }

    private BigDecimal recargo(VentaResumen v) {
        BigDecimal suma = BigDecimal.ZERO;
        for (Venta l : v.getLineas()) {
            if (l.getRecargo() != null) {
                suma = suma.add(l.getRecargo());
            }
        }
        return suma;
    }

    private BigDecimal totalFinal(VentaResumen v) {
        return v.getTotal().subtract(descuento(v)).add(recargo(v));
    }

    private String q(BigDecimal monto) {
        return String.format(Locale.US, "Q%,.2f", monto);
    }

    private String html(String s) {
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;");
    }

